import {afterAll,beforeAll,expect,it} from "vitest";
import {PGlite} from "@electric-sql/pglite";
import {drizzle} from "drizzle-orm/pglite";
import {migrate} from "drizzle-orm/pglite/migrator";
import {planningMonth,reviewGoalOpening,moveBudget,reserveCash,savePlan,savePayday,saveAnnualFund,removeSchedule} from "../monthly-planning";
import {nextPayday,nextAnnualDue,annualFunding} from "../payday-model";
const db=new PGlite(),user={workspace:"w",actor:"owner"},day="2024-03-01";
beforeAll(async()=>{
  await migrate(drizzle(db),{migrationsFolder:"./drizzle"});
  await db.exec(`INSERT INTO users(id,email,password_hash) VALUES('owner','o@example.invalid','x'),('viewer','v@example.invalid','x');
    INSERT INTO workspaces(id,name,owner_id) VALUES('w','Home','owner'),('other','Other','owner');
    INSERT INTO workspace_members(workspace_id,user_id,role) VALUES('w','owner','owner'),('w','viewer','viewer');
    INSERT INTO accounts(id,workspace_id,name,type,initial_balance) VALUES('cash','w','Cash','cash',100),('card','w','Card','card',1000);
    INSERT INTO categories(id,workspace_id,name,kind) VALUES('food','w','Food','expense'),('bills','w','Bills','expense');
    INSERT INTO goals(id,workspace_id,name,target_amount,saved_amount) VALUES('goal','w','Trip',500,10),('next','w','Next',500,0);
    INSERT INTO transactions(id,workspace_id,account_id,category_id,date,type,amount) VALUES
      ('purchase','w','cash',null,'2024-02-29','expense',35),('future','w','cash',null,'2024-03-05','income',500);
    INSERT INTO purchase_allocations VALUES('purchase','food',30),('purchase','bills',5);
    INSERT INTO transfers(id,workspace_id,from_account_id,to_account_id,date,amount) VALUES('transfer','w','cash','card','2024-02-25',5);
  `);
},60000);
afterAll(()=>db.close());
it("uses nonoverlapping pay periods across leap day and keeps expected income separate from posted cash",async()=>{
  const initial=await planningMonth(db,user,"2024-02",day);
  expect(nextPayday("2024-02-23","weekly")).toBe("2024-03-01");
  expect(nextPayday("2024-12-27","biweekly")).toBe("2025-01-10");
  const p={account:"cash",start:"2024-02-23",next:"2024-03-01",cadence:"weekly",expected:"800",limit:"50",version:0};
  await savePayday(db,user,p);
  const irregular={...p,start:"2024-03-01",next:"2024-03-19",cadence:"irregular",expected:"900"};
  await savePayday(db,user,irregular);
  await expect(savePayday(db,user,{...irregular,start:"2024-02-29"})).rejects.toThrow("already has");
  await expect(savePayday(db,{workspace:"w",actor:"viewer"},p)).rejects.toThrow("Access");
  await expect(savePayday(db,user,{...p,account:"card"})).rejects.toThrow("active cash");
  const feb=await planningMonth(db,user,"2024-02",day);
  expect(feb.paydays).toHaveLength(1);
  expect(feb.paydays[0]).toMatchObject({spent:"35.00",income:"0.00",remaining:"15.00"});
  const march=await planningMonth(db,user,"2024-03",day);
  expect(march.paydays).toHaveLength(1);
  expect(march.paydays[0]).toMatchObject({spent:"0.00",income:"0.00",expected:"900.00"});
  expect((await planningMonth(db,user,"2024-03","2024-03-05")).paydays[0].income).toBe("500.00");
  expect(march.accounts).toEqual(initial.accounts);
  await savePayday(db,user,{...irregular,limit:"45",version:1});
  await expect(removeSchedule(db,user,{...irregular,kind:"pay",version:1})).rejects.toThrow("changed");
  await removeSchedule(db,user,{...irregular,kind:"pay",version:2});
});
it("bases annual targets on reserved cash, excludes manual progress and leaves savings intact on schedule removal",async()=>{
  const goal={goal:"goal",due:"2024-05-31",version:0};
  await saveAnnualFund(db,user,goal);
  const reserve={id:crypto.randomUUID(),account:"cash",goal:"goal",amount:"7",release:false};
  await reserveCash(db,user,reserve,day);
  expect((await planningMonth(db,user,"2024-03",day)).annual[0]).toMatchObject({
    target:"500.00",reserved:"7.00",gap:"493.00",months:3,monthly:"164.34",
  });
  expect(annualFunding("500","550","2024-02-29","2024-03-01")).toEqual({gap:"0.00",months:0,monthly:null});
  expect(annualFunding("500","100","2025-01-01","2024-12-31").monthly).toBe("200.00");
  expect(nextAnnualDue("2024-02-29")).toBe("2025-02-28");
  await expect(saveAnnualFund(db,user,goal)).rejects.toThrow("changed");
  await removeSchedule(db,user,{kind:"annual",goal:"goal",version:1});
  expect((await planningMonth(db,user,"2024-03",day)).held[0].amount).toBe("7.00");
  await reserveCash(db,user,{...reserve,id:crypto.randomUUID(),release:true},day);
});
it("starts at the explicit period and recalculates carry after a late edit, including overspending and reset",async()=>{
  const base={category:"food",month:"2023-12",amount:"20.00",rollover:true,version:0};
  await savePlan(db,user,base);
  expect((await planningMonth(db,user,"2023-11",day)).periods).toEqual([]);
  const read=async(m:string)=>(await planningMonth(db,user,m,day)).periods[0];
  expect(await read("2024-02")).toMatchObject({carry:"40.00",spent:"30.00",remaining:"30.00"});
  await savePlan(db,user,{...base,month:"2024-01",amount:"0"});
  expect(await read("2024-03")).toMatchObject({carry:"-10.00",remaining:"-10.00"});
  await db.exec("INSERT INTO transactions(id,workspace_id,account_id,category_id,date,type,amount) VALUES('late','w','cash','food','2024-01-31','expense',3.05)");
  expect(await read("2024-03")).toMatchObject({carry:"-13.05"});
  await db.exec("DELETE FROM transactions WHERE id='late'");
  await savePlan(db,user,{...base,month:"2024-02",rollover:false,amount:"0"});
  expect(await read("2024-03")).toMatchObject({carry:"0.00",remaining:"0.00"});
  await expect(savePlan(db,user,base)).rejects.toThrow("changed");
  await expect(savePlan(db,{...user,actor:"viewer"},base)).rejects.toThrow("Access");
});
it("prevents two goals reserving the same posted cash, replays safely and bounds releases",async()=>{
  const book=()=>planningMonth(db,user,"2024-03",day);
  const a={id:crypto.randomUUID(),account:"cash",goal:"goal",amount:"50",release:false};
  const before=await book();
  expect(before.accounts.find(r=>r.id==="cash")?.free).toBe("60.00");
  const race=await Promise.allSettled([reserveCash(db,user,a,day),reserveCash(db,user,{...a,id:crypto.randomUUID(),goal:"next"},day)]);
  expect(race.filter(r=>r.status==="fulfilled")).toHaveLength(1);
  const saved=(await book()).held[0];
  const receipt=(await db.query<{id:string}>("SELECT id FROM goal_reservations WHERE delta=50")).rows[0];
  await reserveCash(db,user,{...a,id:receipt.id,goal:saved.goal},day);
  expect((await book()).accounts[0]).toMatchObject({balance:"60.00",free:"10.00"});
  await expect(reserveCash(db,user,{...a,id:crypto.randomUUID(),goal:saved.goal,release:true,amount:"51"},day)).rejects.toThrow("less");
  await expect(reserveCash(db,user,{...a,id:crypto.randomUUID(),account:"card"},day)).rejects.toThrow();
  await expect(reserveCash(db,{workspace:"other",actor:"owner"},a,day)).rejects.toThrow();
  await reserveCash(db,user,{...a,id:crypto.randomUUID(),goal:saved.goal,release:true},day);
  expect((await book()).accounts).toEqual(before.accounts);
  expect((await db.query("SELECT saved_amount::text FROM goals WHERE id='goal'")).rows).toEqual([{saved_amount:"10.00"}]);
});

it("moves only the available monthly remainder, preserves history on retry and applies each category's rollover",async()=>{
  await db.exec(`INSERT INTO categories(id,workspace_id,name,kind) VALUES
    ('travel','w','Travel','expense'),('gifts','w','Gifts','expense'),('outside','other','Outside','expense');
    INSERT INTO transactions(id,workspace_id,account_id,category_id,date,type,amount)
    VALUES('fare','w','cash','travel','2024-12-22','expense',15.43)`);
  const month="2024-12",day="2025-01-15";
  await savePlan(db,user,{month,category:"travel",amount:"30",rollover:true,version:0});
  await savePlan(db,user,{month,category:"gifts",amount:"10",rollover:false,version:0});
  const initial=await planningMonth(db,user,month,day);
  const move={month,id:crypto.randomUUID(),source:"travel",destination:"gifts",amount:"10.07",note:"Holiday gifts"};
  await expect(moveBudget(db,{...user,actor:"viewer"},move,day)).rejects.toThrow("Access");
  await expect(moveBudget(db,user,{...move,destination:"outside"},day)).rejects.toThrow("Both categories");
  await expect(moveBudget(db,user,{...move,destination:"travel"},day)).rejects.toThrow("different");
  await expect(moveBudget(db,user,{...move,amount:"14.58"},day)).rejects.toThrow("less");
  await expect(moveBudget(db,user,{...move,amount:"0"},day)).rejects.toThrow();
  const competing={...move,id:crypto.randomUUID()};
  const writes=await Promise.allSettled([moveBudget(db,user,move,day),moveBudget(db,user,competing,day)]);
  expect(writes.filter(w=>w.status==="fulfilled")).toHaveLength(1);
  const saved=writes[0].status==="fulfilled"?move:competing;
  await moveBudget(db,user,saved,day);
  await expect(moveBudget(db,user,{...saved,amount:"2"},day)).rejects.toThrow("already");
  const updated=await planningMonth(db,user,month,day);
  expect(updated.moves).toHaveLength(1);
  expect(updated.moves[0]).toMatchObject({id:saved.id,source:"travel",destination:"gifts",amount:"10.07",note:"Holiday gifts"});
  expect(updated.periods.find(p=>p.category==="travel")).toMatchObject({base:"30.00",moved:"-10.07",spent:"15.43",remaining:"4.50"});
  expect(updated.periods.find(p=>p.category==="gifts")).toMatchObject({base:"10.00",moved:"10.07",remaining:"20.07"});
  expect(updated.accounts).toEqual(initial.accounts);
  expect(updated.held).toEqual(initial.held);
  const next=await planningMonth(db,user,"2025-01",day);
  expect(next.periods.find(p=>p.category==="travel")).toMatchObject({carry:"4.50",moved:"0.00",remaining:"34.50"});
  expect(next.periods.find(p=>p.category==="gifts")).toMatchObject({carry:"0.00",moved:"0.00",remaining:"10.00"});
  expect(next.moves).toEqual([]);
  const viewer=await planningMonth(db,{...user,actor:"viewer"},month,day);
  expect(viewer.moves).toEqual(updated.moves);
});

it("preserves opening entries and counts only reviewed separate savings alongside real reservations",async()=>{
  await db.exec("INSERT INTO goals(id,workspace_id,name,target_amount,saved_amount) VALUES ('review','w','Review example',200,80)");
  const hold={id:crypto.randomUUID(),account:"cash",goal:"review",amount:"20",release:false};
  await reserveCash(db,user,hold,day);
  await saveAnnualFund(db,user,{goal:"review",due:"2024-05-31",version:0});
  const book=()=>planningMonth(db,user,"2024-03",day);
  const before=await book();
  const progress=async()=>(await book()).progress.find(g=>g.id==="review");
  expect(await progress()).toMatchObject({opening:"80.00",reserved:"20.00",outside:"0.00",confirmed:"20.00",reviewed:false});
  const review={id:crypto.randomUUID(),goal:"review",opening:"80",reserved:"20",outside:"30.55",version:0};
  await expect(reviewGoalOpening(db,{...user,actor:"viewer"},review)).rejects.toThrow("Access");
  await expect(reviewGoalOpening(db,{...user,workspace:"other"},review)).rejects.toThrow();
  await expect(reviewGoalOpening(db,user,{...review,outside:"80.01"})).rejects.toThrow();
  await expect(reviewGoalOpening(db,user,{...review,reserved:"19"})).rejects.toThrow("changed");
  await reviewGoalOpening(db,user,review);
  await reviewGoalOpening(db,user,review);
  const saved=await book();
  expect(saved.accounts).toEqual(before.accounts);
  expect(saved.held).toEqual(before.held);
  expect(await progress()).toMatchObject({confirmed:"50.55",reviewed:true,version:1});
  expect(saved.annual.find(a=>a.goal==="review")).toMatchObject({outside:"30.55",reserved:"20.00",gap:"149.45",monthly:"49.82"});
  await expect(reviewGoalOpening(db,user,{...review,outside:"5"})).rejects.toThrow("already");
  await expect(reviewGoalOpening(db,user,{...review,id:crypto.randomUUID()})).rejects.toThrow("changed");
  await reserveCash(db,user,{...hold,id:crypto.randomUUID(),release:true},day);
  expect(await progress()).toMatchObject({outside:"30.55",confirmed:"30.55"});
  await db.exec("UPDATE goals SET saved_amount=81 WHERE id='review'");
  expect(await progress()).toMatchObject({opening:"81.00",outside:"0.00",confirmed:"0.00",reviewed:false,version:1});
  await reviewGoalOpening(db,user,{...review,id:crypto.randomUUID(),opening:"81",version:1,reserved:"0",outside:"0"});
  expect(await progress()).toMatchObject({opening:"81.00",outside:"0.00",confirmed:"0.00",reviewed:true,version:2});
  expect((await db.query("SELECT count(*)::int AS count FROM goal_opening_reviews WHERE goal_id='review'")).rows).toEqual([{count:2}]);
  expect((await db.query("SELECT opening::text FROM goal_opening_reviews WHERE goal_id='review' ORDER BY version")).rows).toEqual([{opening:"80.00"},{opening:"81.00"}]);
});
